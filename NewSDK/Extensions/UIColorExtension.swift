import UIKit

extension UIColor {

    /// Creates a color from a six-digit hexadecimal RGB string.
    ///
    /// The string is parsed with `Scanner.scanHexInt64`; alpha is always 1. Pass the digits without a `#` prefix.
    ///
    /// - Parameter hex: The color as `RRGGBB`, for example `"FA5D03"`.
    convenience init(hex: String) {
        let scanner = Scanner(string: hex)
        var rgbValue: UInt64 = 0
        scanner.scanHexInt64(&rgbValue)
        let r = (rgbValue & 0xff0000) >> 16
        let g = (rgbValue & 0xff00) >> 8
        let b = rgbValue & 0xff
        self.init(
            red: CGFloat(r) / 0xff,
            green: CGFloat(g) / 0xff,
            blue: CGFloat(b) / 0xff, alpha: 1
        )
    }
}
